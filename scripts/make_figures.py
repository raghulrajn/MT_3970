"""Generate every thesis figure from MLflow artifacts - deterministically.

THE RULE: every figure in your thesis is produced by a function in this
file. No hand-made screenshots, no notebook one-offs. If a figure cannot
be regenerated by ``uv run python scripts/make_figures.py``, it does not
go into the thesis. This is checked at submission (tests/test_submission.py).

Inputs allowed: the MLflow run of your registered model (metrics, params,
artifacts) and the datasets under $DATA_DIR. Nothing else - no local
files outside the repo, no manual preprocessing.

Usage:
    uv run python scripts/make_figures.py                  # latest registered model
    uv run python scripts/make_figures.py --run_id <id>    # specific run
    uv run python scripts/make_figures.py --output figures/

Add a figure: write a ``fig_<name>(ctx)`` function, register it in FIGURES.
Each function receives a FigureContext and saves into ``ctx.output_dir``.
"""

