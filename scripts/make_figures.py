#: Register every thesis figure here: {figure_name: function}.
FIGURES = {
    "loss_curves": fig_loss_curves,
    # "prediction_example": fig_prediction_example,
}


# ---------------------------------------------------------------------------


def latest_registered_run_id(client: MlflowClient) -> str:
    """Run id behind the newest registered model version (any name)."""
    versions = client.search_model_versions()
    if not versions:
        raise SystemExit(
            "No registered model found. Register your best run first:\n"
            "  uv run evaluate.py --run_id <id> --datasets all --register"
        )
    latest = max(versions, key=lambda v: int(v.version))
    return latest.run_id


def main() -> None:
    """Generate all registered figures."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run_id", help="MLflow run id (default: latest registered)")
    parser.add_argument("--output", default="figures", help="Output directory")
    parser.add_argument("--only", nargs="*", help="Generate only these figures")
    args = parser.parse_args()

    mlflow.set_tracking_uri(TRACKING_URI)
    client = MlflowClient()
    run_id = args.run_id or latest_registered_run_id(client)

    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)
    setup_plot_for_thesis()

    ctx = FigureContext(client=client, run_id=run_id, output_dir=output_dir)
    names = args.only or list(FIGURES)
    for name in names:
        logger.info(f"generating '{name}' from run {run_id}")
        FIGURES[name](ctx)

    logger.info(f"done: {len(names)} figure(s) in {output_dir}/")


if __name__ == "__main__":
    main()
