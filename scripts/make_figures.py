import mlflow  # noqa: E402
from mlflow.tracking import MlflowClient  # noqa: E402

from src.visualization.config import setup_plot_for_thesis  # noqa: E402

logger = logging.getLogger(__name__)

TRACKING_URI = "sqlite:///./mlruns/mlflow.db"


@dataclass
class FigureContext:
    """Everything a figure function may read from."""

    client: MlflowClient
    run_id: str
    output_dir: Path

    def save(self, fig, name: str) -> None:
        """Save a figure as PDF (for LaTeX) and PNG (for quick viewing)."""
        for ext in ("pdf", "png"):
            path = self.output_dir / f"{name}.{ext}"
            fig.savefig(path, bbox_inches="tight", dpi=300)
        plt.close(fig)
        logger.info(f"wrote {self.output_dir / name}.pdf/.png")


# ---------------------------------------------------------------------------
# Figure functions - one per thesis figure. ADD YOURS BELOW.
# ---------------------------------------------------------------------------


def fig_loss_curves(ctx: FigureContext) -> None:
    """Training and validation loss over epochs (works for every run)."""
    fig, ax = plt.subplots()
    for metric, label in [("train/loss", "train"), ("val/loss", "validation")]:
        history = ctx.client.get_metric_history(ctx.run_id, metric)
        if not history:
            logger.warning(f"metric '{metric}' not found in run {ctx.run_id}")
            continue
        history.sort(key=lambda m: m.step)
        ax.plot([m.step for m in history], [m.value for m in history], label=label)
    ax.set_xlabel("Step")
    ax.set_ylabel("Loss")
    ax.legend()
    ctx.save(fig, "loss_curves")


